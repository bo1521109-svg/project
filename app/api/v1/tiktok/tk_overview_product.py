def _make_mock_item(name, min_val=5000, max_val=500000):
    return {
        "name": name,
        "value": random.randint(min_val, max_val),
        "changeRate": round(random.uniform(-45, 55), 2),
        "sales": random.randint(min_val, max_val),
        "volume": random.randint(10, 50000),
        "salesChange": round(random.uniform(-35, 45), 2),
        "volumeChange": round(random.uniform(-40, 50), 2),
        "blueOceanIndex": round(random.uniform(10, 98), 1),
    }


def _sort_items(items, sort_by):
    sort_key_map = {
        "sales": "value",
        "volume": "volume",
        "salesChange": "salesChange",
        "volumeChange": "volumeChange",
        "blueOceanIndex": "blueOceanIndex",
    }
    sort_key = sort_key_map.get(sort_by, "value")
    items.sort(key=lambda x: x.get(sort_key, 0), reverse=True)
    return items


@router.get("/level1")
async def product_overview_level1(
    sort_by: Optional[str] = Query("sales", description="排序"),
):
    random.seed(42)
    items = []
    for code, cat in CATEGORY_TREE.items():
        # TikTok商品大盘排除这四个一级类目，与商品搜索保持一致
        if code in ('culture', 'adult-products'):
            continue
        item = _make_mock_item(cat["name"])
        item["code"] = code
        item["subCategoryCount"] = len(cat["children"])
        has_l3 = any(
            len(l2.get("children", [])) > 0 
            for l2 in cat["children"].values()
        ) if cat["children"] else False
        item["hasLevel3"] = has_l3
        items.append(item)
    items = _sort_items(items, sort_by)
    return {
        "code": 200,
        "data": {"categories": items, "total": len(items)},
        "message": "success",
    }


@router.get("/level2")
async def product_overview_level2(
    parent_code: str = Query(..., description="一级类目 code"),
    sort_by: Optional[str] = Query("sales", description="排序"),
):
    if parent_code not in CATEGORY_TREE:
        return {"code": 404, "data": None, "message": f"未找到类目: {parent_code}"}

    random.seed(hash(parent_code) % 10000)
    cat = CATEGORY_TREE[parent_code]
    items = []
    for l2_code, l2_info in cat["children"].items():
        item = _make_mock_item(l2_info["name"])
        item["code"] = l2_code
        l3_list = l2_info.get("children", [])
        item["hasLevel3"] = len(l3_list) > 0 if isinstance(l3_list, list) else False
        item["subCategoryCount"] = len(l3_list) if isinstance(l3_list, list) else 0
        items.append(item)

    items = _sort_items(items, sort_by)
    return {
        "code": 200,
        "data": {
            "parentName": cat["name"],
            "parentCode": parent_code,
            "categories": items,
            "total": len(items),
        },
        "message": "success",
    }


